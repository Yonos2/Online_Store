CREATE TABLE IF NOT EXISTS public.product_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(200) NOT NULL,
    action VARCHAR(10) NOT NULL
        CHECK (action IN ('added', 'updated', 'deleted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS product_notifications_created_at_idx
    ON public.product_notifications (created_at DESC);

CREATE TABLE IF NOT EXISTS public.customer_product_notification_reads (
    customer_id BIGINT NOT NULL
        REFERENCES public.users (id) ON DELETE CASCADE,
    notification_id BIGINT NOT NULL
        REFERENCES public.product_notifications (id) ON DELETE CASCADE,
    read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (customer_id, notification_id)
);
